<?php
namespace app\modules\build\views\preview\bootstrap;

use app\modules\build\views\code\Base_Code_Fragment;
use app\modules\build\views\preview\Alpine;
use app\modules\build\views\preview\Alpinejs_Code_Fragment;
use app\modules\build\views\preview\Html_Code_Fragment;
use app\modules\build\views\preview\Html_Code_Helper;
use app\modules\build\views\preview\Preview_View;
use app\modules\build\views\preview\Valuable_View;
use app\modules\build\views\preview\ValueList_View;
use function yangzie\__;


class Pagination_View extends Preview_View implements Valuable_View{
    use Bootstrap_Popup,Html_Code_Helper, Alpine{
        Alpine::build_code as alpineBuildCode;
    }
    protected function css_map()
    {
        $cssArray = parent::css_map();
        unset($cssArray['backgroundTheme'],$cssArray['foregroundTheme'],$cssArray['paginationSizing']);
        $cssArray['-'] = 'd-flex gap-2 align-items-center';
        return $cssArray;
    }
    protected function style_map($meta=null, $state = 'normal')
    {
        $styleArray = parent::style_map($meta, $state);
        unset($styleArray['background-color'],$styleArray['color']);
        return $styleArray;
    }
    protected function output_as_prop($outputAs, $outputData)
    {
        if (strtolower($outputAs) == 'value'){
            return null;
        }
        return parent::output_as_prop($outputAs, $outputData); // TODO: Change the autogenerated stub
    }

    protected function linkStyle($inputDataName, $outputdata)
    {
        $styleArray = parent::style_map();
        $backgroundColor = $styleArray['background-color']
            ? $styleArray['background-color'].";border-color:{$this->data['meta']['style']['background-color']}!important;"
            : '';
        $color = $styleArray['color'] ?: '';
        if (!$backgroundColor && !$color) return NULL;
        return "`\${alpinejs_in_array(\$el, '{$inputDataName}', {$outputdata}) ? '{$backgroundColor}' : '{$color}'}`";
    }
    protected function linkCss($inputDataName, $outputdata) {
        $cssArray = parent::css_map();
        $styleArray = parent::style_map();
        if ($cssArray['backgroundTheme'] && !$styleArray['background-color']) {
            $backgroundTheme = @$this->data['meta']['css']['backgroundTheme'];
            $activeLinkCss = $cssArray['backgroundTheme'] . ' text-light ' . @$this->cssTranslate['borderColorClass'][$backgroundTheme]?:NULL;
        }

        $linkCss = @$cssArray['foregroundTheme'] && !$styleArray['color'] ? $cssArray['foregroundTheme'] : '';
        $rst = "{'page-link': true";
        if ($activeLinkCss) $rst .= ",'".$activeLinkCss."': alpinejs_in_array(\$el, '{$inputDataName}', {$outputdata})";
        if ($linkCss) $rst .= ",'".$linkCss."': !alpinejs_in_array(\$el, '{$inputDataName}', {$outputdata})";
        $rst .= "}";
        return $rst;
    }
    protected function itemCss($inputDataName, $outputdata) {
        $cssArray = parent::css_map();
        $activeCss = !$cssArray['backgroundTheme']?'active':'';

        $rst = "{'page-item remove-radius': true";
        if ($activeCss) $rst .= ",'{$activeCss}': alpinejs_in_array(\$el, '{$inputDataName}', {$outputdata})";
        $rst .= "}";
        return $rst;
    }

    public function build_ui()
    {
        $outputData = $this->get_output_datas($outputDataNames);
        $inputDataName = $this->get_input_data_name($inputIsArr);
        $myid = $this->myid();
        $space =  $this->indent();
        $total = intval($this->data['meta']['custom']['total']);
        $size = intval($this->data['meta']['custom']['pageSize']);
        if($total<=0) $total = 100;
        if($size<=0) $size = 10;
        $outputDataName = $this->get_output_data_name('VALUE', $outputData['VALUE'], $outputDataNames['VALUE']);

        echo "{$space}<nav";
        echo $this->output_main_attrs(false);// 在下面输出事件
        echo $this->wrap_output(':data-default', $this->get_iterator_data_name()?:$outputDataNames['VALUE']);
        echo ">".PHP_EOL;
        echo $this->indent(1) . '<ul';
        echo $this->wrap_output('class', $this->get_pagination_css());
        echo '>'.PHP_EOL;

        $this->build_item();

        $space =  $this->indent();
        echo $this->indent(1) . "</ul>".PHP_EOL;

        // total
        echo $this->indent(1) . '<div x-text="';
        echo $outputDataName ? sprintf(__('`${%s} items`'), $outputDataName) : sprintf(__("'%s items'"), $total);
        echo '">';
        echo "</div>".PHP_EOL;

        // pagesize
        $limits = [10,20,30,50,100];
        if (!in_array($size, $limits)) {
            $limits[] = $size;
        }
        sort($limits);
        $selectSize = "";
        $inputSize = "";
        $btnSize = "";
        if ($this->data['meta']['css']['paginationSizing']){
            $selectSize = 'form-select-'.$this->data['meta']['css']['paginationSizing'];
            $inputSize = 'form-control-'.$this->data['meta']['css']['paginationSizing'];
            $btnSize = 'btn-'.$this->data['meta']['css']['paginationSizing'];
        }
        echo $this->indent(1) . '<select class="form-select '.$selectSize.'" @change="'.$myid.'_update_pages('.$total.', '.($outputDataName?:'null').', '.$inputDataName.', $event.target.value)" style="width: 100px">'.PHP_EOL;
        foreach ($limits as $limit){
            echo $this->indent(2) .  "<option value='{$limit}'>";
            echo  sprintf(__("%s item/page"), $limit);
            echo "</option>".PHP_EOL;
        }
        echo $this->indent(1) . "</select>".PHP_EOL;


        echo $this->indent(1) . '<div class="d-flex align-items-center gap-1">';
        echo __("goto");
        echo '<input type="number" min="1" x-model="'.$myid.'_goto" class="form-control '.$inputSize.'" style="width: 100px">';
        echo '<button type="button" @click="'.$inputDataName.'='.$myid.'_goto" class="btn btn-light '.$btnSize.'">';
        echo __("OK");
        echo '</button>';
        echo "</div>".PHP_EOL;

        echo "{$space}</nav>".PHP_EOL;
    }
    protected function get_pagination_css(){
        $class = ["pagination mb-0"];
        $cssMap = parent::css_map();
        if ($cssMap['paginationSizing']){
            $class[] = $cssMap['paginationSizing'];
        }
        return join(' ', $class);
    }
    private function build_item()
    {
        $outputData = $this->get_output_datas($outputDataNames);
        $inputDataName = $this->get_input_data_name($inputIsArr);
        $myid = $this->myid();

        $total = intval($this->data['meta']['custom']['total']);
        $size = intval($this->data['meta']['custom']['pageSize']);
        if($total<=0) $total = 100;
        if($size<=0) $size = 10;

        echo $this->indent(1).'<template x-for="item in '.$myid.'_pages" :key="item">'.PHP_EOL;
        echo $this->indent(1) . '<li';
        echo $this->wrap_output(':class',  $this->itemCss($inputDataName, "item"));
        echo '>'.PHP_EOL;

        echo $this->indent(2) . '<a';
        echo $this->wrap_output(':class', $this->linkCss($inputDataName, "item"));
        echo $this->wrap_output(':data-value', "item");
        echo $this->wrap_output('x-text',  "item");
        $this->output_event_listen_props();
        echo PHP_EOL;
        echo $this->indent(2).$this->wrap_output(":style", $this->linkStyle($inputDataName, "item"));
        echo ' href="javascript:;"></a>'.PHP_EOL;

        echo $this->indent(1) . '</li>'.PHP_EOL;

        echo $this->indent(1).'</template>'.PHP_EOL;
    }
    public function build_code(): Base_Code_Fragment
    {
        $fragment = $this->alpineBuildCode();
        $myid = $this->myid();
        $code = <<<PAGINATION
{$myid}_update_pages(totalCount, outputDataName, inputDataName, pageSize){
    this.{$myid}_pages = alpinejs_pagination_pages(totalCount, outputDataName, inputDataName, pageSize );
},
PAGINATION;

        $inputDataName = $this->get_input_data_name($inputIsArr);
        $outputData = $this->get_output_datas($outputDataNames);
        $total = intval($this->data['meta']['custom']['total']);
        $size = intval($this->data['meta']['custom']['pageSize']);
        if($total<=0) $total = 100;
        if($size<=0) $size = 10;
        $outputDataName = $this->get_output_data_name('VALUE', $outputData['VALUE'], $outputDataNames['VALUE']);

        $fragment->add_code(Html_Code_Fragment::SECTION_EVENT, $code);
        $fragment->add_code(Html_Code_Fragment::SECTION_INIT, 'this.'.$myid.'_update_pages('.$total.', '.($outputDataName?"this.{$outputDataName}":"null").', this.'.$inputDataName.', '.$size.');');
        $fragment->add_code(Html_Code_Fragment::SECTION_INIT, 'this.$watch("'.$inputDataName.'", (value, oldValue) => {
    this.'.$myid.'_update_pages('.$total.', '.($outputDataName?"this.{$outputDataName}":"null").', this.'.$inputDataName.', value);
})');
        $fragment->add_code(Html_Code_Fragment::SECTION_DATA_DEFINE, "{$myid}_pages:[],");
        $fragment->add_code(Html_Code_Fragment::SECTION_DATA_DEFINE, "{$myid}_goto:'',");
        return $fragment;
    }
}
